import 'dotenv/config';
import argon2 from 'argon2';
import {pool} from './db.js';
const username=process.env.ADMIN_USERNAME?.trim();
const password=process.env.ADMIN_PASSWORD;
if(!username||!password||password.length<12) throw new Error('Set ADMIN_USERNAME and ADMIN_PASSWORD (12+ characters)');
const exists=await pool.query('SELECT 1 FROM users WHERE username=$1',[username]);
if(exists.rowCount) throw new Error('User already exists; seed does not reset passwords');
const hash=await argon2.hash(password,{type:argon2.argon2id});
await pool.query("INSERT INTO users(name,username,password_hash,role) VALUES($1,$2,$3,'admin')",['Administrador',username,hash]);
console.log('Administrator created');
await pool.end();
